import React from 'react'
import type { LiveTurn } from '../types/liveTurn'

interface PrintViewProps {
  sessionId: string
  theme: string
  liveTurns: LiveTurn[]
}

function formatTimestamp(ts: string | number): string {
  try {
    const d = new Date(typeof ts === 'number' ? ts : ts)
    return d.toLocaleString()
  } catch {
    return String(ts)
  }
}

export const PrintView: React.FC<PrintViewProps> = ({ sessionId, theme, liveTurns }) => {
  const maxLevel = Math.max(...liveTurns.map((t) => t.level ?? 0), 0)
  const rounds: LiveTurn[][] = []
  for (let i = 0; i <= maxLevel; i++) {
    rounds.push(liveTurns.filter((t) => (t.level ?? 0) === i))
  }

  return (
    <div className="print-view">
      {/* Header */}
      <div className="print-header">
        <h1>Seldon Lattice - Debate Transcript</h1>
        <div className="print-meta">
          <span><strong>Theme:</strong> {theme}</span>
          <span><strong>Session:</strong> {sessionId}</span>
          <span><strong>Date:</strong> {new Date().toLocaleDateString()}</span>
          <span><strong>Turns:</strong> {liveTurns.length}</span>
        </div>
      </div>

      {/* Audit Summary */}
      <div className="print-section">
        <h2>Audit Trail Summary</h2>
        <table className="print-table">
          <tbody>
            <tr><td>Total Rounds</td><td>{maxLevel + 1}</td></tr>
            <tr><td>Total Turns</td><td>{liveTurns.length}</td></tr>
            <tr><td>Speakers</td><td>{[...new Set(liveTurns.map((t) => t.speaker))].join(', ')}</td></tr>
          </tbody>
        </table>
      </div>

      {/* Rounds */}
      {rounds.map((turns, i) => (
        <div key={i} className="print-section">
          <h2>Round {i + 1}</h2>
          {turns.map((turn) => (
            <div key={turn.id} className="print-turn">
              <div className="print-turn-header">
                <span className="print-speaker">{turn.speaker.toUpperCase()}</span>
                <span className="print-role">{turn.dialecticRole}</span>
                <span className="print-time">{formatTimestamp(turn.timestamp)}</span>
              </div>
              <div className="print-content">{turn.content}</div>
              {turn.metrics && (
                <div className="print-metrics">
                  {turn.metrics.qualityScore != null && <span>Quality: {turn.metrics.qualityScore.toFixed(1)}%</span>}
                  {turn.metrics.ceremonyScore != null && <span>Ceremony: {turn.metrics.ceremonyScore.toFixed(1)}/8</span>}
                  {turn.metrics.similarityScore != null && <span>Similarity: {turn.metrics.similarityScore.toFixed(2)}</span>}
                  {turn.metrics.ascentScore != null && <span>Ascent: {turn.metrics.ascentScore.toFixed(3)}</span>}
                  {turn.metrics.joinMediation != null && <span>Join mediation: {turn.metrics.joinMediation.toFixed(3)}</span>}
                  {turn.metrics.joinNovelty != null && <span>Join novelty: {turn.metrics.joinNovelty.toFixed(3)}</span>}
                  {turn.metrics.irreducibleTension != null && <span>Irreducible tension: {turn.metrics.irreducibleTension.toFixed(3)}</span>}
                </div>
              )}
              {turn.isSustained && <div className="print-metrics"><span>Sustained theme</span></div>}
              {(turn.remainingDissensus || turn.unresolvedTensions?.length || turn.repeatsPremise != null || turn.tensionIntensity != null) && (
                <div className="print-metrics">
                  {turn.remainingDissensus && <span>Remaining dissensus: {turn.remainingDissensus}</span>}
                  {turn.repeatsPremise != null && <span>Repeats premise: {(turn.repeatsPremise * 100).toFixed(1)}%</span>}
                  {turn.unresolvedTensions?.length ? <span>Unresolved tensions: {turn.unresolvedTensions.join('; ')}</span> : null}
                  {turn.tensionIntensity != null && <span>Tension intensity: {turn.tensionIntensity.toFixed(3)}</span>}
                </div>
              )}
            </div>
          ))}
        </div>
      ))}

      {/* Footer */}
      <div className="print-footer">
        <p>Generated by Seldon Lattice - Auditable AI Reasoning Platform</p>
        <p>Session {sessionId} · {liveTurns.length} turns · {maxLevel + 1} rounds</p>
      </div>
    </div>
  )
}

export default PrintView
